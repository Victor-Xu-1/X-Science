BIN="${1:-$ROOT_DIR/dist/x-science}"

export X_SCIENCE_GOAL_STRICT="${X_SCIENCE_GOAL_STRICT:-1}"
export X_SCIENCE_GOAL_ALLOWED_PARTIAL="${X_SCIENCE_GOAL_ALLOWED_PARTIAL:-x-science-link-im}"

